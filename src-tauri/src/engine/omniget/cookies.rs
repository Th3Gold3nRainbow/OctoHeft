use crate::engine::omniget::OmnigetCookieEntry;
use chrono::Utc;
use std::collections::HashSet;
use std::path::{Path, PathBuf};
use url::Url;
use uuid::Uuid;

/// RAII handle for a disposable Netscape HTTP Cookie File.
/// Deletes the file automatically when dropped so session cookies are never left behind on disk,
/// and isolates yt-dlp's exit-time cookie jar updates from overwriting shared state.
pub struct TempCookieFile {
    path: PathBuf,
}

impl TempCookieFile {
    pub fn path(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempCookieFile {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.path);
    }
}

fn sanitize_field(input: &str) -> String {
    input.replace(['\t', '\r', '\n'], "")
}

/// Converts structured browser cookie entries (preferred) or a raw `Cookie:` header string
/// into a temporary Netscape HTTP cookie jar for `yt-dlp --cookies`.
pub fn build_temp_cookie_file(
    target_url: &str,
    cookie_entries: Option<&[OmnigetCookieEntry]>,
    cookie_header: Option<&str>,
) -> Result<Option<TempCookieFile>, String> {
    let entries = cookie_entries.unwrap_or(&[]);
    let raw_header = cookie_header.unwrap_or("").trim();

    if entries.is_empty() && raw_header.is_empty() {
        return Ok(None);
    }

    let default_expiry = Utc::now().timestamp() + 30 * 24 * 3600;
    let mut lines: Vec<String> = Vec::new();
    let mut seen_keys: HashSet<String> = HashSet::new();

    if !entries.is_empty() {
        for entry in entries {
            let name = sanitize_field(entry.name.trim());
            let mut domain = sanitize_field(entry.domain.trim());
            if name.is_empty() || domain.is_empty() {
                continue;
            }
            let path = {
                let cleaned = sanitize_field(entry.path.trim());
                if cleaned.is_empty() {
                    "/".to_string()
                } else {
                    cleaned
                }
            };
            let value = sanitize_field(&entry.value);
            let flag_subdomains = if domain.starts_with('.') {
                "TRUE"
            } else {
                // Prefix host for domain-wide compatibility when yt-dlp accesses subdomains if marked host-only?
                // Keep exact domain flag per MozillaCookieJar spec: leading '.' <-> TRUE
                "FALSE"
            };
            if entry.http_only && !domain.starts_with("#HttpOnly_") {
                domain = format!("#HttpOnly_{}", domain);
            }
            let secure = if entry.secure { "TRUE" } else { "FALSE" };
            let expires = if entry.expires > 0 {
                entry.expires
            } else {
                default_expiry
            };

            let key = format!("{}|{}|{}", domain, path, name);
            if seen_keys.insert(key) {
                lines.push(format!(
                    "{}\t{}\t{}\t{}\t{}\t{}\t{}",
                    domain, flag_subdomains, path, secure, expires, name, value
                ));
            }
        }
    }

    // Backfill any pairs passed solely via Cookie header string
    if !raw_header.is_empty() {
        let domains = infer_domains_for_url(target_url);
        for part in raw_header.split(';') {
            let Some((raw_k, raw_v)) = part.split_once('=') else {
                continue;
            };
            let name = sanitize_field(raw_k.trim());
            let value = sanitize_field(raw_v.trim());
            if name.is_empty() {
                continue;
            }
            for domain in &domains {
                let already_present = seen_keys.iter().any(|k| {
                    k.ends_with(&format!("|{}", name))
                        && (k.starts_with(domain.as_str())
                            || k.starts_with(&format!("#HttpOnly_{}", domain)))
                });
                if !already_present {
                    let sub_flag = if domain.starts_with('.') { "TRUE" } else { "FALSE" };
                    let key = format!("{}|/|{}", domain, name);
                    if seen_keys.insert(key) {
                        lines.push(format!(
                            "{}\t{}\t/\tTRUE\t{}\t{}\t{}",
                            domain, sub_flag, default_expiry, name, value
                        ));
                    }
                }
            }
        }
    }

    if lines.is_empty() {
        return Ok(None);
    }

    let mut content = String::from("# Netscape HTTP Cookie File\n# Generated by OctoHeft\n\n");
    for line in &lines {
        content.push_str(line);
        content.push('\n');
    }

    let path = std::env::temp_dir().join(format!("octoheft_cookies_{}.txt", Uuid::new_v4()));
    std::fs::write(&path, content.as_bytes())
        .map_err(|e| format!("Failed creating temporary cookie file: {}", e))?;

    Ok(Some(TempCookieFile { path }))
}

fn infer_domains_for_url(target_url: &str) -> Vec<String> {
    if let Ok(parsed) = Url::parse(target_url.trim()) {
        if let Some(host) = parsed.host_str() {
            let h = host.to_ascii_lowercase();
            if h == "youtube.com"
                || h.ends_with(".youtube.com")
                || h == "youtu.be"
                || h == "youtube-nocookie.com"
                || h.ends_with(".youtube-nocookie.com")
            {
                return vec![".youtube.com".to_string(), ".google.com".to_string()];
            }
            let parts: Vec<&str> = h.split('.').collect();
            if parts.len() >= 2 {
                let root = format!(".{}.{}", parts[parts.len() - 2], parts[parts.len() - 1]);
                return vec![root];
            }
            return vec![h];
        }
    }
    vec![".youtube.com".to_string()]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_netscape_cookie_generation_and_cleanup() {
        let entries = vec![
            OmnigetCookieEntry {
                domain: ".youtube.com".to_string(),
                path: "/".to_string(),
                secure: true,
                expires: 0,
                http_only: true,
                name: "SID".to_string(),
                value: "abc123\r\n".to_string(),
            },
            OmnigetCookieEntry {
                domain: "www.youtube.com".to_string(),
                path: "/watch".to_string(),
                secure: false,
                expires: 1_900_000_000,
                http_only: false,
                name: "PREF".to_string(),
                value: "tz=Europe.Paris".to_string(),
            },
        ];

        let created_path: PathBuf;
        {
            let tmp = build_temp_cookie_file(
                "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
                Some(&entries),
                Some("SID=abc123; VISITOR_INFO1_LIVE=xyz"),
            )
            .expect("cookie file build failed")
            .expect("expected Some(TempCookieFile)");

            created_path = tmp.path().to_path_buf();
            let text = std::fs::read_to_string(&created_path).unwrap();
            assert!(text.starts_with("# Netscape HTTP Cookie File\n"));
            assert!(text.contains("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t"));
            assert!(!text.contains("\r\nabc"));
            assert!(text.contains("www.youtube.com\tFALSE\t/watch\tFALSE\t1900000000\tPREF\ttz=Europe.Paris"));
            assert!(text.contains("VISITOR_INFO1_LIVE\txyz"));
        }

        assert!(
            !created_path.exists(),
            "Disposable cookie file must be deleted on Drop"
        );
    }
}

