fn escape_rc_string(input: &str) -> String {
    let mut escaped = String::with_capacity(input.len());
    for ch in input.chars() {
        match ch {
            '"' => escaped.push_str("\"\""),
            '\\' => escaped.push_str("\\\\"),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            _ => escaped.push(ch),
        }
    }
    escaped
}

fn enrich_windows_rc_and_recompile(out_path: &std::path::Path) {
    let rc_path = out_path.join("resource.rc");
    let Ok(rc_content) = std::fs::read_to_string(&rc_path) else {
        return;
    };

    let major = std::env::var("CARGO_PKG_VERSION_MAJOR").unwrap_or_else(|_| "0".into());
    let minor = std::env::var("CARGO_PKG_VERSION_MINOR").unwrap_or_else(|_| "1".into());
    let patch = std::env::var("CARGO_PKG_VERSION_PATCH").unwrap_or_else(|_| "0".into());
    let four_part_ver = format!("{major}.{minor}.{patch}.0");

    let description = std::env::var("CARGO_PKG_DESCRIPTION")
        .ok()
        .filter(|s| !s.trim().is_empty())
        .unwrap_or_else(|| "OctoHeft High-Speed Download Accelerator".to_string());

    let mut updated_lines: Vec<String> = Vec::new();
    let mut lines = rc_content.lines().peekable();
    let mut saw_manifest = false;

    while let Some(line) = lines.next() {
        let trimmed = line.trim();
        if trimmed.starts_with("VALUE \"FileDescription\",") {
            updated_lines.push(format!(
                "VALUE \"FileDescription\", \"{}\"",
                escape_rc_string(&description)
            ));
            continue;
        }
        if trimmed.starts_with("VALUE \"FileVersion\",") {
            updated_lines.push(format!(
                "VALUE \"FileVersion\", \"{}\"",
                escape_rc_string(&four_part_ver)
            ));
            continue;
        }
        if trimmed.starts_with("VALUE \"ProductVersion\",") {
            updated_lines.push(format!(
                "VALUE \"ProductVersion\", \"{}\"",
                escape_rc_string(&four_part_ver)
            ));
            continue;
        }
        if trimmed == "1 24" {
            saw_manifest = true;
            // Skip original manifest block generated by tauri-build
            if let Some(&next_line) = lines.peek() {
                if next_line.trim() == "{" {
                    let _ = lines.next();
                    for inner in lines.by_ref() {
                        if inner.trim() == "}" {
                            break;
                        }
                    }
                }
            }

            let manifest_xml = format!(
                r#"<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <assemblyIdentity version="{four_part_ver}" processorArchitecture="*" name="com.antigravity.octoheft" type="win32" />
  <description>{}</description>
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
    <security>
      <requestedPrivileges>
        <requestedExecutionLevel level="asInvoker" uiAccess="false" />
      </requestedPrivileges>
    </security>
  </trustInfo>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}" />
      <supportedOS Id="{{1f676c76-80e1-4239-95bb-83d0f6d0da78}}" />
      <supportedOS Id="{{4a2f28e3-53b9-4441-ba9c-d69d4a4a6e38}}" />
      <supportedOS Id="{{35138b9a-5d96-4fbd-8e2d-a2440225f93a}}" />
    </application>
  </compatibility>
  <dependency>
    <dependentAssembly>
      <assemblyIdentity
        type="win32"
        name="Microsoft.Windows.Common-Controls"
        version="6.0.0.0"
        processorArchitecture="*"
        publicKeyToken="6595b64144ccf1df"
        language="*"
      />
    </dependentAssembly>
  </dependency>
</assembly>"#,
                description
                    .replace('&', "&amp;")
                    .replace('<', "&lt;")
                    .replace('>', "&gt;")
            );

            updated_lines.push("1 24".to_string());
            updated_lines.push("{".to_string());
            for mline in manifest_xml.lines() {
                updated_lines.push(format!("\" {} \"", escape_rc_string(mline.trim())));
            }
            updated_lines.push("}".to_string());
            continue;
        }

        updated_lines.push(line.to_string());
    }

    if !saw_manifest {
        return;
    }

    let mut new_rc = updated_lines.join("\n");
    new_rc.push('\n');

    if std::fs::write(&rc_path, &new_rc).is_err() {
        return;
    }

    let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    if target_env != "msvc" {
        let lib_res = out_path.join("libresource.a");
        let target_arch = match std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() {
            Ok("x86_64") => "pe-x86-64",
            Ok("aarch64") => "pe-aarch64-little",
            _ => "pe-i386",
        };
        let windres_bin = std::env::var("RC").unwrap_or_else(|_| "windres".to_string());
        let status = std::process::Command::new(&windres_bin)
            .args([
                "--input",
                &rc_path.to_string_lossy(),
                "--output",
                &lib_res.to_string_lossy(),
                "--include-dir",
                &out_path.to_string_lossy(),
                "--output-format=coff",
                "--target",
                target_arch,
                "-c",
                "65001",
            ])
            .status()
            .expect("failed to invoke windres to compile enriched Windows VERSIONINFO resource");
        assert!(
            status.success(),
            "windres failed compiling enriched Windows VERSIONINFO resource with {status}"
        );
    }
}

fn main() {
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=icons/icon.ico");

    tauri_build::build();

    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        if let Ok(out_dir) = std::env::var("OUT_DIR") {
            let out_path = std::path::Path::new(&out_dir);
            enrich_windows_rc_and_recompile(out_path);

            // Ensure Windows test executables (both `--lib --test` unit tests and integration tests)
            // embed the Common-Controls v6 manifest and PE VERSIONINFO cleanly.
            for candidate in ["libresource.a", "resource.lib"] {
                let res_path = out_path.join(candidate);
                if res_path.exists() {
                    println!("cargo:rustc-link-arg-tests={}", res_path.display());
                    break;
                }
            }
        }
    }
}

